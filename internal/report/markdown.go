package report

import (
	"bytes"
	"fmt"
	"strings"
)

func (r *Report) Markdown() ([]byte, error) {
	var b bytes.Buffer

	fmt.Fprintf(&b, "# Security Assessment Report - %s\n\n", r.Project.Name)
	fmt.Fprintf(&b, "- **Project:** %s (`%s`)\n", r.Project.Name, r.Project.ID)
	fmt.Fprintf(&b, "- **Generated:** %s\n", r.GeneratedAt)
	fmt.Fprintf(&b, "- **Scope of work:** %d requests, %d endpoints\n\n", r.Stats.Requests, r.Stats.Endpoints)

	b.WriteString("## Summary\n\n")
	fmt.Fprintf(&b, "| Metric | Count |\n|---|---|\n")
	fmt.Fprintf(&b, "| Requests captured | %d |\n", r.Stats.Requests)
	fmt.Fprintf(&b, "| Endpoints discovered | %d |\n", r.Stats.Endpoints)
	fmt.Fprintf(&b, "| Findings (non-FP) | %d |\n", r.Stats.Findings)
	fmt.Fprintf(&b, "| Notes | %d |\n\n", r.Stats.Notes)

	b.WriteString("### Findings by severity\n\n")
	if r.Stats.Findings == 0 {
		b.WriteString("_No findings._\n\n")
	} else {
		b.WriteString("| Severity | Count |\n|---|---|\n")
		for _, s := range r.SortedSeverities() {
			fmt.Fprintf(&b, "| %s | %d |\n", s, r.FindingsBySeverity[s])
		}
		b.WriteString("\n")
	}

	if len(r.Findings) > 0 {
		b.WriteString("## Findings\n\n")
		for i := range r.Findings {
			f := &r.Findings[i]
			fmt.Fprintf(&b, "### %d. %s\n\n", i+1, f.Title)
			fmt.Fprintf(&b, "- **Severity:** %s\n", f.Severity)
			fmt.Fprintf(&b, "- **Confidence:** %s\n", f.Confidence)
			fmt.Fprintf(&b, "- **Type:** %s (`%s`)\n", f.Type, f.CheckID)
			if f.EndpointID != "" {
				fmt.Fprintf(&b, "- **Endpoint:** %s (`%s`)\n", f.EndpointURL, f.EndpointID)
			}
			if f.RequestID != "" {
				fmt.Fprintf(&b, "- **Request:** `%s`", f.RequestID)
				if f.ResponseCode > 0 {
					fmt.Fprintf(&b, " → HTTP %d", f.ResponseCode)
				}
				b.WriteString("\n")
			}
			if f.Retested {
				b.WriteString("- **Retested:** yes — re-verified after reporting\n")
			}
			fmt.Fprintf(&b, "- **Reported:** %s\n\n", f.CreatedAt)
			if f.Explanation != "" {
				fmt.Fprintf(&b, "**Explanation:**\n\n%s\n\n", f.Explanation)
			}
			if f.Remediation != "" {
				fmt.Fprintf(&b, "**Remediation:**\n\n%s\n\n", f.Remediation)
			}
			if len(f.Evidence) > 0 {
				b.WriteString("**Evidence:**\n\n```json\n")
				b.WriteString(r.EvidenceText(*f))
				b.WriteString("\n```\n\n")
			}
		}
	}

	if len(r.Endpoints) > 0 {
		fmt.Fprintf(&b, "## Endpoints (%d)\n\n", len(r.Endpoints))
		b.WriteString("| Method | Path | Host | Requests | Last seen |\n|---|---|---|---|---|\n")
		for _, e := range r.Endpoints {
			fmt.Fprintf(&b, "| %s | %s | %s | %d | %s |\n",
				e.Method, e.PathTemplate, e.Host, e.RequestCount, e.LastSeen)
		}
		b.WriteString("\n")
	}

	if len(r.Notes) > 0 {
		fmt.Fprintf(&b, "## Notes (%d)\n\n", len(r.Notes))
		for _, n := range r.Notes {
			if n.ObjectID != "" {
				fmt.Fprintf(&b, "- `%s` → `%s`: %s\n", n.ID, n.ObjectID, n.Content)
			} else {
				fmt.Fprintf(&b, "- `%s`: %s\n", n.ID, n.Content)
			}
		}
		b.WriteString("\n")
	}

	if len(r.Scope) > 0 {
		b.WriteString("## Scope\n\n")
		for _, s := range r.Scope {
			fmt.Fprintf(&b, "- **%s** (%s): `%s`\n", s.Action, s.PatternType, s.Pattern)
		}
		b.WriteString("\n")
	}

	b.WriteString("---\n")
	b.WriteString("_Generated by AgentBurp._\n")
	return b.Bytes(), nil
}

func (r *Report) MarkdownSummary() ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "## AgentBurp summary — %s\n\n", r.Project.Name)
	fmt.Fprintf(&b, "%d findings (%s)\n\n", r.Stats.Findings, strings.Join(r.SortedSeverities(), ", "))
	for i := range r.Findings {
		f := &r.Findings[i]
		fmt.Fprintf(&b, "- **[%s] %s** — `%s` @ %s (confidence %s)\n",
			strings.ToUpper(f.Severity), f.Title, f.CheckID, f.EndpointURL, f.Confidence)
	}
	return b.Bytes(), nil
}
